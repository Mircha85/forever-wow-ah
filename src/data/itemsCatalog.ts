export function getQualityColor(quality: number): string {
  switch (quality) {
    case 0: return 'text-slate-400'; // Poor
    case 1: return 'text-slate-100'; // Common
    case 2: return 'text-emerald-400'; // Uncommon
    case 3: return 'text-sky-400'; // Rare
    case 4: return 'text-purple-400'; // Epic
    case 5: return 'text-amber-400'; // Legendary
    case 6: return 'text-rose-400'; // Artifact
    case 7: return 'text-cyan-300'; // Heirloom
    default: return 'text-slate-200';
  }
}

export function getQualityBorderColor(quality: number): string {
  switch (quality) {
    case 0: return 'border-slate-600';
    case 1: return 'border-slate-500';
    case 2: return 'border-emerald-500/60';
    case 3: return 'border-sky-500/60';
    case 4: return 'border-purple-500/60';
    case 5: return 'border-amber-500/80';
    case 6: return 'border-rose-500';
    default: return 'border-slate-600';
  }
}
